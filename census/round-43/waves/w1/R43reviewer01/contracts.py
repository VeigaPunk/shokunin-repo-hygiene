import ast
import contextlib
import io
import os
from pathlib import Path
import runpy
import shutil
import subprocess
import tempfile
import types

LANE = Path('/home/vgpnk/Projects/shokunin/souji-shokunin')
SEAT = LANE / '.ufo/waves/round-43/w1/R43reviewer01'
REV = 'f8c805dbfa7f45814cf9a7270fa8bbffb41a8373'
S = Path('/fast/scratch/hyaku/souji-r43/R43reviewer01')
S.mkdir(parents=True, exist_ok=True)
os.environ['TMPDIR'] = str(S)
tempfile.tempdir = str(S)
try:
    print('PROBE memorizer generated by literal frozen AST assignments:')
    tree = ast.parse((SEAT/'c2-counter.py').read_text())
    main = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'main')
    selected = [n for n in main.body if isinstance(n, (ast.Assign, ast.AugAssign)) and
                ((isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'mem_lines') or
                 (isinstance(n, ast.AugAssign) and isinstance(n.target, ast.Name) and n.target.id == 'mem_lines'))]
    ns = {}
    exec(compile(ast.Module(body=selected, type_ignores=[]), '<frozen mem_lines assignments>', 'exec'), ns)
    mem = S/'memorizer.py'; mem.write_text('\n'.join(ns['mem_lines'])+'\n')
    p = subprocess.run(['python3', '-B', str(mem), '--prereg', str(S/'absent')], capture_output=True)
    print('rc=', p.returncode, 'last_stderr=', p.stderr.decode().splitlines()[-1])
    print('PROBE c3 target predicate (all unrelated legs mocked green; primary fixture rc=1, n10_before wrong-fails):')
    c3 = runpy.run_path(str(SEAT/'c3-counter.py'), run_name='review_import')
    g = c3['main'].__globals__
    old_show = g['show']
    g['show'] = lambda root, rev, path, scratch: b'candidate' if path == g['FIXTURE'] else old_show(root, rev, path, scratch)
    def completed(rc, out):
        return types.SimpleNamespace(returncode=rc, stdout=out.encode(), stderr=b'')
    def fixture(b, tool, work, scratch, timeout=300):
        if work.endswith('/nb'):
            p = completed(1, 'case-unrelated=FAIL\nSUMMARY cases=17 pass=16 fail=1\n')
        elif work.endswith('/pc'):
            p = completed(1, 'SUMMARY cases=17 pass=17 fail=0\n')
        elif '/old_' in work or '/prior_' in work:
            p = completed(0, 'SUMMARY cases=1 pass=1 fail=0\n')
        elif b == g['SNIFF'].encode() or '/mut_S' in tool:
            p = completed(1, 'SUMMARY cases=17 pass=16 fail=1\n')
        else:
            p = completed(0, 'SUMMARY cases=17 pass=17 fail=0\n')
        return p, 0, False, work+'/_fixture.py'
    g['run_fixture'] = fixture
    actual_run = subprocess.run
    def run(argv, **kw):
        if any('shim_wrapper.py' in x for x in argv):
            Path(kw['env']['SHIM_LOG']).write_text('invoke\n'*17)
            return completed(0, '')
        return actual_run(argv, **kw)
    g['subprocess'] = types.SimpleNamespace(run=run, PIPE=subprocess.PIPE, DEVNULL=subprocess.DEVNULL, TimeoutExpired=subprocess.TimeoutExpired)
    g['stderr_discrimination_selftest'] = lambda: True
    g['direct_n10_probe'] = lambda *a: 'ok'
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        rc = c3['main'](['--root',str(LANE),'--rev',REV,'--scratch',str(S)])
    print(out.getvalue().strip())
    print('return=',rc)
finally:
    shutil.rmtree(S)
    print('scratch_removed=',not S.exists())
