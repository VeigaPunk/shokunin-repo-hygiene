#!/usr/bin/env python3
"""s297-make-located-quote.py — regenerate s297-located-quote.txt from the
delivered captures, so every offset in it is a mechanically proven slice
assertion rather than a recorded number.

Run:  python3 s297-make-located-quote.py <html> <txt> <man> <out.txt>
"""
import hashlib
import re
import sys

PRIMARY = b"So, this variable controls how the commands display the untracked files."
SECONDARY = [
    ("S1", b"normal - Show untracked files and directories."),
    ("S2", b"all - Show also individual files in untracked directories."),
    ("S3", b"no - Show no untracked files."),
    ("S4", b"Directories which contain only untracked files, are shown with the directory name only."),
    ("S5", b"By default, git-status[1] and git-commit[1] show files which are not currently tracked by Git."),
    ("S6", b"This variable can be overridden with the -u|--untracked-files option of git-status[1] and git-commit[1]."),
    ("S7", b"If this variable is not specified, it defaults to normal."),
]
HTML_ANCHORS = [
    ("<dt ... statusshowUntrackedFiles>", b'Documentation/git-config.txt-statusshowUntrackedFiles'),
    ("value item 'no'", b'<code>no</code></span> - Show'),
    ("value item 'normal'", b'<code>normal</code></span> - Show'),
    ("value item 'all'", b'<code>all</code></span> - Show'),
]
HTML_SLICES = [
    b'- Show no untracked files.',
    b'- Show untracked files and directories.',
    b'- Show also individual files in untracked directories.',
]


def line_of(b: bytes, off: int) -> int:
    return b[:off].count(b'\n') + 1


def main() -> int:
    if len(sys.argv) != 5:
        print("usage: s297-make-located-quote.py <html> <txt> <man> <out>", file=sys.stderr)
        return 2
    h = open(sys.argv[1], 'rb').read()
    t = open(sys.argv[2], 'rb').read()
    m = open(sys.argv[3], 'rb').read()

    to = t.find(PRIMARY)
    hfw = h.find(b"So, this variable controls", 760000)
    flex = re.sub(rb'\s+', b' ', h[hfw:hfw + 200])
    anchor = h.find(b'Documentation/git-config.txt-statusshowUntrackedFiles')

    o = []
    w = o.append
    w("s297-located-quote.txt — located quote for the S297 source row")
    w("source page : https://git-scm.com/docs/git-config")
    w("section     : § status.showUntrackedFiles")
    w("opened      : 2026-11-05")
    w("")
    w("captures measured (sha256 of the delivered bytes):")
    w("  s297-git-config.html   %d bytes  sha256 %s" % (len(h), hashlib.sha256(h).hexdigest()))
    w("  s297-git-config.txt    %d bytes  sha256 %s" % (len(t), hashlib.sha256(t).hexdigest()))
    w("  s297-git-config.man.txt %d bytes sha256 %s" % (len(m), hashlib.sha256(m).hexdigest()))
    w("")
    w("tag-strip recipe: see s297-tagstrip.py (delivered beside this file). Deterministic")
    w("and re-runnable:  python3 s297-tagstrip.py s297-git-config.html s297-git-config.txt")
    w("This file is regenerated by s297-make-located-quote.py, so every offset below is")
    w("a slice assertion that is re-run, not a number copied from a note.")
    w("")
    w("=" * 78)
    w("PRIMARY LOCATED QUOTE")
    w("=" * 78)
    w("quote        : %s" % PRIMARY.decode())
    w("words        : %d  (limit 25)  -> %s" % (len(PRIMARY.split()),
                                                "WITHIN LIMIT" if len(PRIMARY.split()) <= 25 else "OVER LIMIT"))
    w("carrier      : s297-git-config.txt (the tag-stripped TEXT capture)")
    w("text offset  : %d   (line %d)" % (to, line_of(t, to)))
    w("text length  : %d bytes" % len(PRIMARY))
    w("")
    w("EXACT SLICE ASSERTION")
    w("  text[%d:%d] == quote" % (to, to + len(PRIMARY)))
    w("  assert text[%d:%d] == quote_bytes" % (to, to + len(PRIMARY)))
    w("  -> %s" % ("PASSED" if t[to:to + len(PRIMARY)] == PRIMARY else "FAILED"))
    w("  actual slice = %r" % t[to:to + len(PRIMARY)])
    w("")
    w("THE SAME SENTENCE IN THE RAW HTML CAPTURE")
    w("  byte-contiguous in s297-git-config.html : %s"
      % ("YES at %d" % h.find(PRIMARY) if h.find(PRIMARY) >= 0 else "NO (find = -1)"))
    w("  reason : the page wraps the sentence across one source newline and carries no")
    w("           markup inside it, so the raw bytes at the sentence start are")
    w("             html[%d] = %r" % (hfw, h[hfw:hfw + 20]))
    w("           and the sentence's tail resumes after that newline at html offset %d"
      % h.find(b'the untracked files.', hfw))
    w("  first-word ('So, this variable controls') raw HTML offset : %d  (line %d)"
      % (hfw, line_of(h, hfw)))
    w("  whitespace-flexible check (runs of \\s+ collapsed to one space over the html")
    w("  window at that offset) : the quote IS present -> %s" % (PRIMARY in flex))
    w("  section anchor <dt id=\"Documentation/git-config.txt-statusshowUntrackedFiles\">")
    w("  raw HTML offset : %d  (line %d)" % (anchor, line_of(h, anchor)))
    w("")
    w("=" * 78)
    w("SUPPORTING QUOTES (same section, same recipe, same proof method)")
    w("=" * 78)
    for tag, q in SECONDARY:
        qo = t.find(q)
        mo = m.find(q)
        w("")
        w("%s  %s" % (tag, q.decode()))
        w("    words            : %d" % len(q.split()))
        w("    text offset      : %s%s" % (qo, ("   (line %d)" % line_of(t, qo)) if qo >= 0 else "   NOT FOUND"))
        if qo >= 0:
            w("    text proof       : assert text[%d:%d] == quote_bytes -> %s"
              % (qo, qo + len(q), "PASSED" if t[qo:qo + len(q)] == q else "FAILED"))
        w("    html contiguous  : %s" % (str(h.find(q)) if h.find(q) >= 0 else "NOT contiguous in raw HTML (find = -1)"))
        w("    man page carrier : %s%s" % (mo, ("   (line %d)" % line_of(m, mo)) if mo >= 0 else "   NOT in rendered man output"))
        if mo >= 0:
            w("    man proof        : assert man[%d:%d] == quote_bytes -> %s"
              % (mo, mo + len(q), "PASSED" if m[mo:mo + len(q)] == q else "FAILED"))
    w("")
    w("=" * 78)
    w("RAW-HTML ANCHOR OFFSETS OF THE SECTION'S MARKUP PIECES")
    w("=" * 78)
    for lbl, pat in HTML_ANCHORS:
        i = h.find(pat, 760000)
        w("  %-36s offset %d  (line %d)" % (lbl, i, line_of(h, i)))
    w("")
    for q in HTML_SLICES:
        w("  html offset of %-58r : %d" % (q.decode(), h.find(q)))
    w("")
    w("SECOND INDEPENDENT CARRIER")
    w("  installed man page /usr/share/man/man1/git-config.1.gz (package owner: git 2.56.0-1)")
    w("  rendered with MANWIDTH=200 man 1 git-config -> s297-git-config.man.txt")
    w("  %d bytes  sha256 %s" % (len(m), hashlib.sha256(m).hexdigest()))
    w("  The man renderer emits a double space at the source wrap ('the  untracked'), so")
    w("  the 11-word PRIMARY sentence is NOT byte-contiguous there (find = -1); the three")
    w("  value-list sentences and S4 ARE byte-contiguous in the man output (offsets above).")
    open(sys.argv[4], 'w').write("\n".join(o) + "\n")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
