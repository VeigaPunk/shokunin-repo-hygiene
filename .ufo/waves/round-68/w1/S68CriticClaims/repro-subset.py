#!/usr/bin/env python3
"""S68CriticClaims reproduction driver (read-only against the lane).

Runs the FROZEN counter's own evaluate() on row SUBSETS (never the 42-row counter) against:
  - the candidate writer (census/round-68 candidate blob f70da577, bytes b811ee2a),
  - the 14 frozen battery mutants regenerated by the frozen census/round-68/mutate-writer.py into scratch,
  - three scratch crash-path mutants and one scratch fsmonitor-pin drop (scratch only),
  - two in-process row injections X1 (non-excludes GIT_CONFIG_COUNT) and X2 (repo-local core.fsmonitor hook),
    injected by wrapping m.case_env / m.mutate in THIS process; the frozen counter file is not edited.

Usage: python3 -B repro-subset.py    (writes repro-subset.out next to this file and prints it)
Scratch: $HYAKU_SCRATCH/souji-r68/S68CriticClaims (default /fast/scratch/hyaku). Never /tmp.
"""
import sys, os, shutil, subprocess, hashlib, importlib.util

sys.dont_write_bytecode = True
LANE = "/home/vgpnk/Projects/shokunin/souji-shokunin"
SEAT = os.path.join(LANE, ".ufo/waves/round-68/w1/S68CriticClaims")
S = os.environ.get("HYAKU_SCRATCH") or "/fast/scratch/hyaku"
D = os.path.join(S, "souji-r68", "S68CriticClaims")
for sub in ("cand", "mut", "slots", "work"):
    os.makedirs(os.path.join(D, sub), exist_ok=True)

OUT = []
def log(line=""):
    print(line)
    OUT.append(line)

# 1. candidate and base bytes from git (read-only)
def blob(rev, path, dst):
    data = subprocess.run(["git", "-C", LANE, "show", f"{rev}:{path}"], capture_output=True, check=True).stdout
    with open(dst, "wb") as f:
        f.write(data)
    os.chmod(dst, 0o755)
    return hashlib.sha256(data).hexdigest()

CAND = os.path.join(D, "cand", "candidate.py")
BASE = os.path.join(D, "slots", "base.py")
h_cand = blob("f70da577eb1e1624cc63ab8fd0468565927d9b6a", "tools/souji-receipt-write.py", CAND)
h_base = blob("3639087917eaeb28719d7603110a6ec22782100e", "tools/souji-receipt-write.py", BASE)
log(f"candidate sha256={h_cand} (frozen b811ee2a...: {h_cand.startswith('b811ee2a')})")
log(f"base sha256={h_base} (r67 base a8c47d36...: {h_base.startswith('a8c47d36')})")

# 2. the 14 frozen mutants, regenerated and checked against battery/SHA256SUMS
names = ["K1","K2","K3","K4","K5","K6","K7","K8","M-CD-CALL","M-CD-EMPTY","M-CD-NCABS","M-CD-NCRAW","M-CD-ROOTREL","M-CD-SCRUB"]
subprocess.run(["python3", "-B", os.path.join(LANE, "census/round-68/mutate-writer.py"), CAND,
                os.path.join(D, "mut"), *names], check=True, cwd=D, capture_output=True)
sums = {}
for line in open(os.path.join(LANE, "census/round-68/battery/SHA256SUMS")):
    h, p = line.split(None, 1)
    sums[os.path.basename(p.strip())] = h
bad = [n for n in names if hashlib.sha256(open(os.path.join(D, "mut", n + ".py"), "rb").read()).hexdigest() != sums[n + ".py"]]
log(f"battery mutants matching SHA256SUMS: {len(names) - len(bad)}/14 bad={bad}")

# 3. scratch-only probes (candidate text with one anchored edit each)
cand_src = open(CAND, encoding="utf-8").read()
def mk(name, old, new):
    assert cand_src.count(old) == 1, (name, cand_src.count(old))
    p = os.path.join(D, "mut", name + ".py")
    open(p, "w", encoding="utf-8").write(cand_src.replace(old, new, 1))
    os.chmod(p, 0o755)
    return p
CRASH2 = mk("CRASH-EXIT2", "def write_receipt(ns: argparse.Namespace) -> int:\n",
            "def write_receipt(ns: argparse.Namespace) -> int:\n    sys.exit(2)\n")
CRASH1 = mk("CRASH-EXIT1", "def write_receipt(ns: argparse.Namespace) -> int:\n",
            "def write_receipt(ns: argparse.Namespace) -> int:\n    raise RuntimeError('r68 probe')\n")
GITFAIL = mk("GIT-PLUMBING-FAIL", '"-c", "core.fsmonitor=false",', '"--r68-no-such-option", "-c", "core.fsmonitor=false",')
FSM = mk("FSM-PIN-DROP", '"-c", "core.fsmonitor=false",', "")

# 4. frozen counter module, imported read-only (no edits, no bytecode)
spec = importlib.util.spec_from_file_location("c1c", os.path.join(LANE, "census/round-68/c1-counter.py"))
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
rows, err = m.load_matrix(os.path.join(LANE, "census/round-68/c1-matrix.tsv"))
assert rows and not err, err
byl = {r[0]: r for r in rows}
log(f"frozen matrix rows={len(rows)} spec_agreement={m.spec_agreement(rows, m.CASE_SPECS)}")

# in-process row injection (wraps case_env / mutate for this process only)
orig_case_env, orig_mutate = m.case_env, m.mutate
def patched_case_env(sp, repo):
    if sp.get("x_cfg"):
        return dict(sp["x_cfg"])
    return orig_case_env(sp, repo)
HOOK_DIR = os.path.join(D, "work", "fsm"); os.makedirs(HOOK_DIR, exist_ok=True)
MARKER = os.path.join(HOOK_DIR, "marker.txt")
HOOK = os.path.join(HOOK_DIR, "hook.sh")
open(HOOK, "w").write(f"#!/bin/sh\npwd >> {MARKER}\nexit 1\n"); os.chmod(HOOK, 0o755)
def patched_mutate(repo, sp):
    orig_mutate(repo, sp)
    if sp.get("x_fsm"):
        subprocess.run(["git", "-C", repo, "config", "core.fsmonitor", HOOK], check=True)
m.case_env, m.mutate = patched_case_env, patched_mutate
m.CASE_SPECS["X1"] = {"name": "x-config-count-filemode-nonexcludes", "env_kind": "replace-base", "mode_change": True,
                      "x_cfg": {"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "core.fileMode", "GIT_CONFIG_VALUE_0": "false"}}
m.CASE_SPECS["X2"] = {"name": "x-fsmonitor-hook-repo-local", "env_kind": "replace-ref-head", "honest": True, "x_fsm": True}
X1ROW = ("X1", "refuse", "RECEIPT-ENV-CONFIG-SET")
X2ROW = ("X2", "accept", "-")

def run(label, slot, sub):
    work = os.path.join(D, "work", label); shutil.rmtree(work, ignore_errors=True); os.makedirs(work)
    res = m.evaluate(sub, BASE, slot, work, None)
    c = res["counts"]
    errs = sum(1 for ln in res["lines"] if " new=error " in ln)
    subset_ok = (c["new_forgeries"] == 0 and c["new_honest"] == res["n_accept"]
                 and c["class_mismatches"] == 0 and res["all_new_match"])
    verdict = "SUBSET-PASS" if subset_ok else ("REFUTED-shape (exit1, zero error rows)" if errs == 0 else "ERROR-ROWS (kill)")
    log(f"--- {label} rows={[r[0] for r in sub]} new_forg={c['new_forgeries']} new_honest={c['new_honest']}/{res['n_accept']} "
        f"class_mis={c['class_mismatches']} error_rows={errs} => {verdict}")
    for ln in res["lines"]:
        if ln.startswith("CASE"):
            log("    " + ln)
    return res

# 5. candidate subset sanity
run("cand", CAND, [byl[l] for l in ["A","W3","W4","W5","W6","E1","E3","MOD2","PK3","PK3h","PK4","PK4h","PK6","PK6h","PK7","PK7h"]])

# 6. battery mutants on their deciding rows
PLAN = [("K1",["E1","E2"]),("K2",["E4","E5","E6"]),("K3",["PK3","PK3h"]),("K4",["E3","PK4","PK4h"]),
        ("K5",["MOD2","MOD3"]),("K6",["PK6","PK6h"]),("K7",["PK7","PK7h"]),("K8",["N3","P13"]),
        ("M-CD-CALL",["W1","W2"]),("M-CD-EMPTY",["W5"]),("M-CD-NCABS",["W6","W3"]),
        ("M-CD-NCRAW",["W3","W6"]),("M-CD-ROOTREL",["W4"]),("M-CD-SCRUB",["W1","W2"])]
for nm, letters in PLAN:
    run(nm, os.path.join(D, "mut", nm + ".py"), [byl[l] for l in letters])

# 7. attack rows: non-excludes config forgery (K1 vs X1), crash paths, fsmonitor pin
run("X1-cand", CAND, [X1ROW])
run("X1-K1", os.path.join(D, "mut", "K1.py"), [X1ROW])
run("CRASH-EXIT2", CRASH2, [byl[l] for l in ["A","C","D","E1"]])
run("CRASH-EXIT1", CRASH1, [byl[l] for l in ["A","C"]])
run("GIT-PLUMBING-FAIL", GITFAIL, [byl[l] for l in ["A","C","E1","PK3"]])

for label, slot in (("X2-cand", CAND), ("X2-FSM-PIN-DROP", FSM)):
    if os.path.exists(MARKER):
        os.remove(MARKER)
    run(label, slot, [X2ROW])
    hits = len(open(MARKER).read().split()) if os.path.exists(MARKER) else 0
    log(f"    repo-local fsmonitor hook executions during {label}: {hits}")

with open(os.path.join(SEAT, "repro-subset.out"), "w", encoding="utf-8") as f:
    f.write("\n".join(OUT) + "\n")
